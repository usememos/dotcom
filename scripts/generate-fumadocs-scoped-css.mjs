import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const require = createRequire(import.meta.url);
const sourcePath = require.resolve("fumadocs-ui/style.css");
const outputPath = join(dirname(fileURLToPath(import.meta.url)), "..", "src/app/(public)/docs/fumadocs-scoped.css");
// `:where()` contributes zero specificity, so scoping only narrows *where* a rule
// applies and never changes how it ranks against project CSS. A bare
// `html:has(#nd-docs-layout)` prefix would add specificity to every Fumadocs rule and
// silently flip cascade winners — e.g. Fumadocs' `.dark` palette would outrank
// fumadocs-theme.css, and its `--radius-*`/`--font-*` would outrank our `:root`.
//
// Detecting Fumadocs' own layout root also avoids a route-marker script: the
// scope is correct in server-rendered HTML and updates automatically on client
// navigation, while still covering portals rendered elsewhere under <html>.
const scope = ":where(html:has(#nd-docs-layout))";

function scopeSelector(selector) {
  if (selector.startsWith(":root") || selector.startsWith(":host")) {
    return selector.replace(/^:(?:root|host)/, scope);
  }

  if (/^html(?=[\s.#:[>+~]|$)/.test(selector)) {
    return selector.replace(/^html/, scope);
  }

  if (/^\.dark(?=[\s.#:[>+~]|$)/.test(selector)) {
    return selector.replace(/^\.dark/, `${scope}.dark`);
  }

  if (/^\[dir=(?:"rtl"|'rtl')\]/.test(selector)) {
    return selector.replace(/^\[dir=(?:"rtl"|'rtl')\]/, `${scope}[dir="rtl"]`);
  }

  return `${scope} ${selector}`;
}

function shouldSkipSelectorScoping(rule) {
  let parent = rule.parent;

  while (parent && parent.type !== "root") {
    if (parent.type === "rule") {
      return true;
    }

    if (parent.type === "atrule" && /(?:^|-)keyframes$/i.test(parent.name)) {
      return true;
    }

    parent = parent.parent;
  }

  return false;
}

const source = await readFile(sourcePath, "utf8");
const root = postcss.parse(source, { from: sourcePath });

// Tailwind's `layout:` variant reverses the selector relationship with
// `#nd-docs-layout:has(&)`. Prefixing its outer utility would substitute `&`
// with `:where(html:has(#nd-docs-layout)) .layout\:...`, which can never be a
// descendant of `#nd-docs-layout`. Keep the outer utility intact and scope the
// nested layout selector instead.
const relationalSelectorParents = new Set();
root.walkRules((rule) => {
  if (!rule.selector.includes(":has(&)")) {
    return;
  }

  let parent = rule.parent;
  while (parent && parent.type !== "root" && parent.type !== "rule") {
    parent = parent.parent;
  }

  if (parent?.type === "rule") {
    relationalSelectorParents.add(parent);
    rule.selector = [...new Set(postcss.list.comma(rule.selector).map(scopeSelector))].join(", ");
  }
});

root.walkRules((rule) => {
  if (!relationalSelectorParents.has(rule) && !shouldSkipSelectorScoping(rule)) {
    // `postcss.list.comma` is the same quote/escape-aware split, from the module
    // already imported here. Assigning `rule.selector` (not `rule.selectors`)
    // keeps the join separator stable, so the generated file stays byte-stable.
    rule.selector = [...new Set(postcss.list.comma(rule.selector).map(scopeSelector))].join(", ");
  }
});

const header = `/* Generated by scripts/generate-fumadocs-scoped-css.mjs. Do not edit directly. */\n`;
await writeFile(outputPath, `${header}${root.toString()}\n`);
